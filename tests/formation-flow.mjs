import { chromium } from 'playwright'
const BASE = process.argv[2] || 'http://127.0.0.1:5173/'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } })
const page = await ctx.newPage()
const errs = []
page.on('pageerror', e => errs.push('PAGEERR ' + e.message))
page.on('console', m => { if (m.type() === 'error' && !m.text().includes('ERR_TUNNEL')) errs.push('CONSOLE ' + m.text()) })
const log = (...a) => console.log(...a)
const st = () => page.evaluate(() => window.__AK__.getState())
const shot = (n) => page.screenshot({ path: `test-results/e2e-${n}.png` })
let fails = 0
const check = (cond, msg) => { log(cond ? 'PASS' : 'FAIL', msg); if (!cond) fails++ }

// 1) 부트 → 오프닝 → 타이틀 → 입력 → 로비
await page.goto(BASE)
await page.waitForSelector('.boot-cta.on', { timeout: 20000 })
await page.mouse.click(640, 360)
await page.waitForTimeout(400)
check(await page.locator('.op').count() === 1, '오프닝 시작')
check(await page.evaluate(() => { const v = document.querySelector('.op video'); return !!v && !v.paused }), '오프닝 영상 재생 중')
const t0 = Date.now()
await page.waitForTimeout(3000); await shot('op-3s')
await page.waitForTimeout(4000); await shot('op-7s')
await page.waitForTimeout(3500); await shot('op-10s')
// 입력 전에 자동 로비 진입하지 않는지
await page.waitForFunction(() => document.querySelector('.op .sr-only')?.textContent === 'PRESS ANY BUTTON', null, { timeout: 20000 })
const tPress = (Date.now() - t0) / 1000
check(tPress > 12.4 && tPress < 16, `영상 속 타이틀(13초) 이후 입력 대기 시작 (${tPress.toFixed(1)}s)`)
const hangul = await page.evaluate(() => /[가-힣]/.test(document.querySelector('.op').innerText))
check(!hangul, '오프닝/타이틀에 한글 없음')
await shot('title')
await page.waitForTimeout(2500)
check(await page.locator('.lb').count() === 0, '입력 없이 로비로 자동 진입하지 않음')
await page.keyboard.press('Enter')
await page.waitForTimeout(2600)
check(await page.locator('.lb').count() === 1, '입력 후 로비 진입')
await shot('lobby-after-entrance')

// 2) 로비 → 편성 → 교체 → 저장 → 로비 → 편성 재진입
await page.click('.lb-m:has-text("편성")')
await page.waitForTimeout(900)
check(await page.locator('.fm').count() === 1, '편성 진입')
const before = (await st()).teams[0].slots
await page.click('.fm-plate-wrap:nth-child(3) .fm-plate-main') // 3번 슬롯(하린)
await page.click('.fm-thumb[aria-label^="나린"]')
await page.waitForTimeout(600)
check(await page.locator('.fm-dirty').count() === 1, '저장 전 변경 표시')
// 이미 팀에 있는 캐릭터(지안) 선택 → 위치 교환
await page.click('.fm-thumb[aria-label^="지안"]')
await page.waitForTimeout(600)
const draftSlots = await page.$$eval('.fm-plate-text strong', (e) => e.map((x) => x.textContent))
log('  draft plates:', draftSlots.join(','))
check(draftSlots[0] === '나린' && draftSlots[2] === '지안', '팀 내 캐릭터 선택 시 위치 교환')
// 저장 없이 뒤로 → 확인 팝업
await page.click('.fm-back')
await page.waitForTimeout(400)
check(await page.locator('.modal h2:has-text("저장하지 않은 변경")').count() === 1, '저장 전 뒤로가기 확인 팝업')
await shot('fm-leave-dialog')
await page.click('.modal button:has-text("계속 편집")')
await page.waitForTimeout(300)
await page.click('.fm-save')
await page.waitForTimeout(700)
const saved = (await st()).teams[0]
check(JSON.stringify(saved.slots) === JSON.stringify(['narin', 'yujin', 'jian', 'doyun']), `저장 반영 ${saved.slots}`)
check(saved.leaderId === 'jian', '리더 유지(지안)')
await page.click('.fm-back')
await page.waitForTimeout(800)
check(await page.locator('.lb').count() === 1, '로비 복귀')
check((await st()).lobby.characterId === 'jian', '로비 대표 캐릭터는 편성 변경과 독립')
await page.click('.lb-m:has-text("편성")')
await page.waitForTimeout(900)
const plates2 = await page.$$eval('.fm-plate-text strong', (e) => e.map((x) => x.textContent))
check(plates2.join() === '나린,유진,지안,도윤', `편성 재진입 시 저장 상태 표시 (${plates2})`)

// 3) 연타: 빠르게 여러 캐릭터를 같은 슬롯에 넣기
await page.click('.fm-plate-wrap:nth-child(2) .fm-plate-main')
for (const n of ['세인', '하린', '세인', '하린', '세인']) await page.click(`.fm-thumb[aria-label^="${n}"]`, { delay: 0 })
await page.waitForTimeout(800)
const figs = await page.$$eval('.fm-fig:not(.ghost) img', (e) => e.map((x) => x.getAttribute('src')))
const plates3 = await page.$$eval('.fm-plate-text strong', (e) => e.map((x) => x.textContent))
check(plates3[1] === '세인' && figs[1].includes('sein'), `연타 후 최종 선택(세인)과 화면 인물 일치 (${plates3} / ${figs[1]})`)
check(await page.locator('.fm-fig.ghost').count() === 0, '퇴장 연출 잔상 정리됨')
await page.click('.fm-save'); await page.waitForTimeout(700)
check((await st()).teams[0].slots[1] === 'sein', '연타 후 저장 결과 일치')

// 4) 팀 전환·이름 변경·리더 지정
await page.click('.fm-team-edit')
await page.fill('.fm-team input', '출근조')
await page.keyboard.press('Enter')
await page.click('.fm-plate-wrap:nth-child(4) .fm-plate-main')
await page.click('.fm-slot-actions button:has-text("리더 지정")')
await page.click('.fm-team-btn:has-text("팀 02")')
await page.waitForTimeout(300)
check(await page.locator('.modal').count() === 1, '저장 전 팀 전환 확인 팝업')
await page.click('.modal button:has-text("저장")')
await page.waitForTimeout(800)
let s = await st()
check(s.teams[0].name === '출근조' && s.teams[0].leaderId === 'doyun', `팀 이름·리더 저장 (${s.teams[0].name}, ${s.teams[0].leaderId})`)
check(s.teams[1].name === '팀 02' && s.activeTeamId === 'team2', '팀 02로 전환, 팀 이름은 해당 팀에만 반영')
// 팀 03 빈 슬롯
await page.click('.fm-team-btn:has-text("팀 03")'); await page.waitForTimeout(500)
check(await page.locator('.fm-empty').count() === 4, '빈 슬롯은 인물 없이 번호·추가 표시')
await page.click('.fm-empty >> nth=0'); await page.click('.fm-thumb[aria-label^="유진"]'); await page.waitForTimeout(300)
await shot('fm-team3')
await page.click('.fm-actions button:has-text("초기화")'); await page.waitForTimeout(400)
check(await page.locator('.fm-empty').count() === 4, '초기화 = 마지막 저장 상태로 되돌림')
await page.click('.fm-actions button:has-text("자동 편성")'); await page.waitForTimeout(500)
check(await page.locator('.fm-fig:not(.ghost)').count() === 4, '자동 편성(임시 규칙) 4명 배치')
await page.click('.fm-save'); await page.waitForTimeout(700)

// 5) 재시작 복원
await page.reload()
await page.waitForTimeout(800)
s = await st()
check(s.teams[0].name === '출근조' && s.teams[0].slots[1] === 'sein' && s.teams[2].slots.filter(Boolean).length === 4, '새로고침 후 저장 상태 복원')
// 6) 영상 재생 실패 → 정적 타이틀 대체
const p2 = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage()
await p2.route('**/assets/video/*.{mp4,webm}', (r) => r.abort())
await p2.goto(BASE)
await p2.waitForSelector('.boot-cta.on', { timeout: 20000 })
await p2.mouse.click(640, 360); await p2.waitForTimeout(1500)
check(await p2.locator('.op-title.static').count() === 1, '영상 실패 시 정적 타이틀로 대체')
await p2.keyboard.press('Space'); await p2.waitForTimeout(1500)
check(await p2.locator('.lb').count() === 1, '정적 타이틀에서도 입력 후 로비 진입')
log('errors:', errs.length ? errs : 'none')
log('FAILS', fails)
await browser.close()
