// 역 로비 배너 슬라이드 + S01 패스 화면 검증. dev 서버 실행 중에: node tests/pass-and-carousel.mjs [BASE]
import { chromium } from 'playwright'
const BASE = process.argv[2] || 'http://127.0.0.1:5173/'
const browser = await chromium.launch()
const page = await (await browser.newContext({ viewport: { width: 1672, height: 941 } })).newPage()
const errs = []
page.on('pageerror', (e) => errs.push('PAGEERR ' + e.message))
page.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('ERR_TUNNEL')) errs.push('CONSOLE ' + m.text()) })
let fails = 0
const check = (c, m) => { console.log(c ? 'PASS' : 'FAIL', m); if (!c) fails++ }
const W = (ms = 500) => page.waitForTimeout(ms)
const st = () => page.evaluate(() => window.__AK__.getState())
const hitLabel = () => page.locator('.screen-active .bc-hit').getAttribute('aria-label')

// 1) 역 로비 배너 슬라이드
await page.goto(BASE + '?screen=lobby'); await W(600)
await page.evaluate(() => window.__AK__.setLobbyTheme('station')); await W(2200)
check(await page.locator('.screen-active .bc-dots button').count() === 3, '배너 3장 = 점 3개(원본 점 9개 대신 실제 장 수)')
check((await hitLabel()).startsWith('픽업 영입'), '첫 장 = 픽업 영입')
await page.click('.screen-active .bc-dots button:nth-child(2)'); await W(900)
check((await hitLabel()).startsWith('S01 패스'), '점 누르면 S01 패스 배너로')
const box = await page.locator('.screen-active .bc-hit').boundingBox()
await page.mouse.move(box.x + box.width * .7, box.y + box.height / 2); await page.mouse.down(); await page.mouse.move(box.x + box.width * .2, box.y + box.height / 2, { steps: 6 }); await page.mouse.up(); await W(900)
check((await hitLabel()).startsWith('FP1 썸머 패스'), '끌어서 넘기기(→ 셋째 장 썸머 패스)')
await page.mouse.move(800, 600); await W(6800)
check((await hitLabel()).startsWith('픽업 영입'), '가만히 두면 자동으로 다음 장(마지막 → 첫 장)')
await page.click('.screen-active .bc-dots button:nth-child(2)'); await W(900)
await page.click('.screen-active .bc-hit'); await W(1200)
check(await page.locator('.screen-active .ui-pass').count() === 1, '패스 배너 누르면 패스 화면')

// 2) 패스 화면
await W(1600)
check((await page.locator('.pp-lv b').textContent()).trim() === '35', '레벨 숫자 0 → 35')
const bw = await page.locator('.pp-bar i').evaluate((e) => e.style.width)
check(bw === '70%', '경험치 막대 35/50 = 70%')
check(await page.locator('.pp-track .ms.done').count() === 4 && await page.locator('.pp-track .ms.next').count() === 1 && await page.locator('.pp-track .ms.final').count() === 1, '마일스톤: 0~30 달성, 40 다음 목표, 50 잠금')
check(await page.locator('.pp-card').count() === 5, 'Premium 보상 카드 5장')
const wallet = JSON.stringify((await st()).wallet)
await page.click('.pp-card-hit[aria-label^="7성 센카"]'); await W(500)
check(await page.locator('.modal h2:has-text("7성 센카")').count() === 1, '보상 카드 → 상세 안내')
await page.keyboard.press('Escape'); await W(400)
await page.click('button[aria-label^="GET PREMIUM"]'); await W(500)
check(await page.locator('.modal:has-text("결제는 아직 연결되지 않았습니다")').count() === 1, 'GET PREMIUM = 결제 미연결 안내')
await page.keyboard.press('Escape'); await W(400)
check(JSON.stringify((await st()).wallet) === wallet, '재화 변화 없음')
await page.click('button[role="tab"]:has-text("Basic")'); await W(500)
check(await page.locator('.pp-basic').count() === 1 && await page.locator('.pp-card').count() === 0, 'Basic = 구성 미정 안내')
await page.click('.screen-active button[aria-label^="MISSIONS"]'); await W(800)
check(await page.locator('.pp-mrow').count() === 6, 'MISSIONS = 일일 미션 6개 진행 상황')
await page.click('.screen-active button[aria-label^="REWARDS"]'); await W(500)
check(await page.locator('.pp-tracks').count() === 1, 'REWARDS로 복귀')
await page.click('.screen-active .pp-back'); await W(900)
check(await page.locator('.screen-active .bc').count() === 1, '뒤로 → 역 로비')
await page.click('.screen-active button[aria-label="전체 메뉴"]'); await W(300)
await page.click('.rl-more button:has-text("패스")'); await W(1000)
check(await page.locator('.screen-active .ui-pass').count() === 1, '역 로비 전체 메뉴 → 패스')

// 3) FP1 썸머 패스 화면
await page.click('.screen-active .pp-back'); await W(900)
await page.evaluate(() => window.__AK__.setLobbyTheme('station')); await W(1500)
await page.click('.screen-active .bc-dots button:nth-child(3)'); await W(900)
await page.click('.screen-active .bc-hit'); await W(3200)
check(await page.locator('.screen-active .ui-spass').count() === 1, '썸머 배너 누르면 썸머 패스 화면')
check((await page.locator('.sp-lv b').textContent()).trim() === '35', '티켓 레벨 0 → 35')
check((await page.locator('.sp-exp').textContent()).replace(/\s/g, '') === '380/1,000', '경험치 0 → 380 / 1,000')
check(await page.locator('.sp-bar i').evaluate((e) => e.style.width) === '38%', '경험치 막대 380/1000 = 38%')
check(await page.locator('.sp-col').count() === 6 && await page.locator('.sp-col.now').count() === 1 && await page.locator('.sp-col.done').count() === 5, '보상 열 Lv.31~36, 현재 Lv.35 강조, 31~35 달성')
const wallet2 = JSON.stringify((await st()).wallet)
await page.click('.sp-col-hit[aria-label^="Lv.34"]'); await W(500)
check(await page.locator('.modal h2:has-text("Lv.34 보상")').count() === 1 && await page.locator('.modal:has-text("여행 상자")').count() === 1, '보상 열 → 레벨별 기본·프리미엄 보상 안내')
await page.keyboard.press('Escape'); await W(400)
await page.click('.sp-col-hit[aria-label^="Lv.36"]'); await W(500)
check(await page.locator('.modal h2:has-text("1레벨 남음")').count() === 1, '미달성 레벨은 남은 레벨 표시')
await page.keyboard.press('Escape'); await W(400)
await page.click('button[aria-label="PREMIUM 보상만 보기"]'); await W(400)
check(await page.locator('.ui-spass.focus-premium').count() === 1 && await page.locator('.sp-dim.basic').first().evaluate((e) => +getComputedStyle(e).opacity > .5), 'PREMIUM = 기본 보상 줄 흐리게')
await page.click('button[aria-label="PREMIUM 보상만 보기"]'); await W(400)
check(await page.locator('.ui-spass.focus-premium').count() === 0, '다시 누르면 모두 보기')
await page.click('button[aria-label="다음 레벨 보상"]'); await W(300)
check(await page.locator('.sp-toast:has-text("Lv.37 이후")').count() === 1, '다음 화살표 = Lv.37 이후 미정 안내')
await page.click('button[aria-label^="GET PREMIUM"]'); await W(500)
check(await page.locator('.modal:has-text("결제는 아직 연결되지 않았습니다")').count() === 1, '썸머 GET PREMIUM = 결제 미연결 안내')
await page.keyboard.press('Escape'); await W(400)
await page.click('button[aria-label="패스 레벨 안내"]'); await W(400)
check(await page.locator('.modal:has-text("다음 레벨까지 620")').count() === 1, '티켓 → 레벨·경험치 안내')
await page.keyboard.press('Escape'); await W(400)
check(JSON.stringify((await st()).wallet) === wallet2, '썸머 패스: 재화 변화 없음')
const ul0 = await page.locator('.sp-uline').evaluate((e) => e.style.left)
await page.click('.screen-active button[aria-label^="MISSIONS"]'); await W(800)
check(await page.locator('.sp-mrow').count() === 6 && await page.locator('.sp-col').count() === 0 && ul0 !== await page.locator('.sp-uline').evaluate((e) => e.style.left), 'MISSIONS = 일일 미션 6개 + 밑줄 이동')
await page.click('.screen-active button[aria-label^="REWARDS"]'); await W(600)
check(await page.locator('.sp-col').count() === 6, 'REWARDS로 복귀')
await page.click('.screen-active button[aria-label="뒤로"]'); await W(900)
check(await page.locator('.screen-active .bc').count() === 1, '썸머 패스 뒤로 → 역 로비')
await page.click('.screen-active button[aria-label="전체 메뉴"]'); await W(300)
await page.click('.rs-menu button:has-text("썸머 패스")'); await W(1000)
check(await page.locator('.screen-active .ui-spass').count() === 1, '역 로비 전체 메뉴 → 썸머 패스')

console.log('errors:', errs.length ? errs : 'none')
console.log('FAILS', fails + (errs.length ? 1 : 0))
await browser.close()
process.exit(fails || errs.length ? 1 : 0)
