// Exercise real input on moving UI, without spending currency. Self-contained dev server.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { createServer } from 'vite'
import { chromium } from 'playwright'
const server = await createServer({ server: { host: '127.0.0.1', port: 5189, strictPort: true } })
await server.listen()
const browser = await chromium.launch({ args: ['--no-sandbox'] })
const errors = []
const results = []
const check = (condition, message) => { assert(condition, message); results.push(message); console.log('PASS', message) }
await mkdir('test-results/ui-motion', { recursive: true })
try {
  const context = await browser.newContext({ viewport: { width: 1672, height: 941 } })
  const page = await context.newPage()
  page.on('pageerror', e => errors.push(e.message))
  const active = () => page.locator('.screen-active')
  const open = async screen => {
    await page.goto(`http://127.0.0.1:5189/?screen=${screen}`, { waitUntil: 'domcontentloaded' })
    await active().locator('.ui-motion').waitFor()
    await page.waitForTimeout(1100)
  }
  const click = async label => { await active().getByRole('button', { name: label, exact: true }).click(); await page.waitForTimeout(450) }
  await open('lobby')
  const wallet = await page.evaluate(() => window.__AK__.getState().wallet)
  const menu = active().getByRole('button', { name: '캐릭터', exact: true })
  const box0 = await menu.boundingBox()
  await menu.hover(); await page.waitForTimeout(280)
  const box1 = await menu.boundingBox()
  check(box1.y < box0.y - 3, '로비 hover: 그림과 클릭 영역이 함께 이동')
  await menu.click(); await page.waitForTimeout(600)
  check(await active().locator('.chars').count() === 1, '움직이는 로비 메뉴 → 캐릭터 목록')
  await open('lobby')
  check(await active().locator('.ui-station').count() === 1, '로비 = 역 로비(카페 로비 폐기)')
  await page.screenshot({ path: 'test-results/ui-motion/station.png' })
  await click('현상수배')
  check(await active().locator('.ct-wanted').count() === 1, '역 겹친 카드의 현상수배 클릭 유지')
  await open('lobby')
  await click('전체 메뉴')
  await page.getByRole('button', { name: '감상 모드', exact: true }).click()
  check(await active().locator('.mg-wrap.hide').count() === 1, '감상 모드는 모션 UI도 숨김')
  await click('UI 다시 표시')
  check(await active().locator('.mg-wrap.hide').count() === 0, 'UI 복구')
  await open('characterDetail')
  check(await active().locator('.ui-title[aria-label="RAON"]').count() === 2, '상세 배경/이름은 독립된 라이브 타이포')
  await click('SKILLS')
  check(await active().locator('.cd2-alt .cd2-row').count() > 0, 'SKILLS 탭 내용 표시')
  await active().getByRole('button', { name: /^STATS/ }).click()
  await page.waitForTimeout(600)
  await active().getByRole('button', { name: 'UPGRADE (성장)', exact: true }).click()
  check(await page.getByRole('button', { name: 'CANCEL', exact: true }).count() === 1, '성장 팝업 정상 열림')
  await page.getByRole('button', { name: 'CANCEL', exact: true }).click()
  await active().getByRole('button', { name: /^세렌/ }).click(); await page.waitForTimeout(700)
  check(await active().locator('.ui-title[aria-label="SEREN"]').count() === 2, '캐릭터 교체 시 타이포와 아트 갱신')
  await page.screenshot({ path: 'test-results/ui-motion/detail-alt.png' })
  await open('recruit')
  await active().getByRole('button', { name: /^상시 배너 SERENITY/ }).click(); await page.waitForTimeout(900)
  check(await active().locator('.ui-rscene.rs-serenity').count() === 1, '다른 영입 배너 전환(SERENITY 시안 화면)')
  await active().getByRole('button', { name: /^한정 배너 주파수/ }).click(); await page.waitForTimeout(700)
  check(await active().locator('.ui-recruit-title').count() === 1, '라온 배너 복귀 시 타이포 재생성')
  await click('확률 정보')
  check(await page.locator('.rate-table').count() === 1, '확률 정보 버튼 클릭 유지')
  await page.keyboard.press('Escape')
  check(JSON.stringify(await page.evaluate(() => window.__AK__.getState().wallet)) === JSON.stringify(wallet), '미리보기/탭 전환으로 재화 변경 없음')
  await page.screenshot({ path: 'test-results/ui-motion/recruit-final.png' })
  // A continuous UI loop actually changes, with videos paused.
  await active().locator('video').evaluateAll(videos => videos.forEach(v => v.pause()))
  const ticker = active().locator('.ui-broadcast-tape > div')
  const before = await ticker.evaluate(el => getComputedStyle(el).transform)
  await page.waitForTimeout(400)
  check(before !== await ticker.evaluate(el => getComputedStyle(el).transform), '영상 정지 상태에서도 UI 방송 띠가 움직임')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await active().locator('.ui-reduced').waitFor({ timeout: 3000 }).catch(() => {})
  check(await active().locator('.ui-reduced').count() === 1, 'OS 모션 감소 반영')
  check(await ticker.evaluate(el => getComputedStyle(el).animationName) === 'none', '모션 감소에서 반복 타이포 정지')
  await page.screenshot({ path: 'test-results/ui-motion/reduced.png' })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.evaluate(() => window.__AK__.updateSettings({ reduceMotion: true }))
  await page.waitForTimeout(150)
  check(await ticker.evaluate(el => getComputedStyle(el).animationName) === 'none', '앱 모션 감소도 UI 반복 정지')
  await page.evaluate(() => window.__AK__.updateSettings({ reduceMotion: false }))
  await page.waitForTimeout(150)
  check(await ticker.evaluate(el => getComputedStyle(el).animationName) === 'uiTicker', '모션 설정 해제 후 UI 반복 복구')

  const mobile = await browser.newContext({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true })
  const mp = await mobile.newPage()
  mp.on('pageerror', e => errors.push(e.message))
  for (const screen of ['lobby', 'characterDetail', 'recruit']) {
    await mp.goto(`http://127.0.0.1:5189/?screen=${screen}`, { waitUntil: 'domcontentloaded' }); await mp.locator('.screen-active .ui-motion').waitFor(); await mp.waitForTimeout(1000)
    check(await mp.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${screen} 모바일 가로 overflow 없음`)
    await mp.screenshot({ path: `test-results/ui-motion/mobile-${screen}.png` })
  }
  await mp.locator('.screen-active').getByRole('button', { name: '상세 정보', exact: true }).tap()
  check(await mp.locator('.modal').count() === 1, '모바일 영입 상세 정보 터치')
  check(errors.length === 0, `브라우저 런타임 오류 없음: ${errors.join(', ')}`)
  console.log(`${results.length} checks passed`)
} finally {
  await browser.close()
  await server.close()
}
